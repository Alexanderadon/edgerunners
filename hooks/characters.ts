// Герой на нужном языке: всё, что он говорит и как подписан. Значок, кадры и имена для /persona — общие.
export const inLang = (who: Hero, lang: Lang): Hero => {
  const en = lang === 'en' ? (EN as Record<string, Partial<Hero>>)[who.id] : undefined

  return en ? { ...who, ...en } : who
}

// aliases: английские имена тоже находятся в /persona.
export const DEFAULT_HERO = 'kadr'

export const heroById = (id: string): Hero =>
  HEROES.find(one => one.id === id) ?? HEROES[0]!

export const findHero = (word: string): Hero | undefined => {
  const key = word.trim().toLowerCase()

  return HEROES.find(one => one.id === key || one.aliases.includes(key) || (EN as Record<string, { name: string }>)[one.id]?.name.toLowerCase().split(' ')[0] === key)
}

// Случайная реплика, но не та же, что была только что.
export const pickLine = (lines: readonly string[], last: string): string => {
  const fresh = lines.length > 1 ? lines.filter(one => one !== last) : lines

  return fresh[Math.floor(Math.random() * fresh.length)] ?? ''
}
